"use strict";

// Static audit of the generated test files for signs that the writer used information outside its specification.
// This cannot prove isolation. It can only find evidence of leakage. Writes results/isolation_audit.md.
// Usage: node scripts/audit_isolation.js
//
// Checks per file:
//  1. Every name taken from the module (mod.X, mod["X"] or destructuring) must appear in the file's own spec.
//  2. The file must not read files. It must not inspect function source. It must not enumerate module exports.
//  3. Comments and strings must not mention source code, implementation or line numbers.
//  4. Tests that fail on the correct code are counted as weak evidence of independence (a copy of the code's
//     behaviour would pass).

const fs = require("node:fs");
const path = require("node:path");
const ROOT = path.resolve(__dirname, "..");

const specFiles = fs.readdirSync(path.join(ROOT, "specs"));
const specText = {};
for (const f of specFiles) specText[f.split("_")[0]] = fs.readFileSync(path.join(ROOT, "specs", f), "utf8");

const runs = fs.readFileSync(path.join(ROOT, "results", "runs.jsonl"), "utf8").trim().split("\n").map((l) => JSON.parse(l));
const runKey = (r) => `${r.spec}/${r.condition}/${r.trial}`;
const runMap = Object.fromEntries(runs.filter((r) => r.source === "generated").map((r) => [runKey(r), r]));

const wordIn = (name, text) => new RegExp(`(^|[^A-Za-z0-9_$])${name.replace(/\$/g, "\\$")}($|[^A-Za-z0-9_$])`).test(text);

const rows = [];
for (const spec of fs.readdirSync(path.join(ROOT, "generated")).sort()) {
  for (const cond of ["basic", "structured"]) {
    const dir = path.join(ROOT, "generated", spec, cond);
    for (const f of fs.readdirSync(dir).sort()) {
      const src = fs.readFileSync(path.join(dir, f), "utf8");
      const trial = f.replace(".test.js", "");
      const names = new Set();
      for (const m of src.matchAll(/\bmod\.([A-Za-z_$][\w$]*)/g)) names.add(m[1]);
      for (const m of src.matchAll(/\bmod\[\s*["'`]([^"'`]+)["'`]\s*\]/g)) names.add(m[1]);
      for (const m of src.matchAll(/(?:const|let|var)\s*\{([^}]*)\}\s*=\s*(?:mod|require\([^)]*\))/g)) {
        for (const part of m[1].split(",")) {
          const n = part.split(":")[0].trim().split("=")[0].trim();
          if (n) names.add(n);
        }
      }
      const outsideSpec = [...names].filter((n) => !wordIn(n, specText[spec]));

      const body = src.split("\n").filter((l) => !/require\(/.test(l)).join("\n");
      const behaviours = [];
      if (/\brequire\(\s*["'](?:node:)?fs["']|readFileSync|readdirSync|node:child_process|child_process/.test(src)) behaviours.push("file or process access");
      if (/\.toString\(\)\s*(?:\.|\)|;)|Function\.prototype\.toString/.test(body) && /mod\.[A-Za-z_$]+\.toString/.test(body)) behaviours.push("inspects function source");
      if (/Object\.(keys|getOwnPropertyNames|entries)\(\s*mod\s*\)/.test(body)) behaviours.push("enumerates module exports");
      const mentions = [];
      for (const l of body.split("\n")) {
        if (/(\/\/|\/\*|\*)/.test(l) && /\b(source code|implementation|the code|src\/|sut\/|line \d+|actual code|looking at|as implemented)\b/i.test(l)) mentions.push(l.trim());
      }
      const r = runMap[`${spec}/${cond}/${trial}`];
      rows.push({ spec, cond, trial, names: [...names], outsideSpec, behaviours, mentions, falseAlarms: r ? r.falseAlarms : null });
    }
  }
}

const flagged = rows.filter((r) => r.outsideSpec.length || r.behaviours.length || r.mentions.length);
let md = "# Isolation audit of generated test files\n\nGenerated by scripts/audit_isolation.js. Do not edit by hand.\n\n";
md += "This is a static check. It can find evidence that a test writer used information outside its specification. It cannot prove that none did, because a writer that read the source and then used only spec-named functions would pass every check here.\n\n";
md += `## Summary\n\n- Files audited: ${rows.length}\n- Files using a module name that does not appear in their own spec: ${rows.filter((r) => r.outsideSpec.length).length}\n- Files with file access, function-source inspection or export enumeration: ${rows.filter((r) => r.behaviours.length).length}\n- Files whose comments mention source code, implementation or line numbers: ${rows.filter((r) => r.mentions.length).length}\n- Files with at least one flag: ${flagged.length}\n- Files with at least one test that fails on correct code (weak evidence the writer did not copy the code's behaviour): ${rows.filter((r) => r.falseAlarms > 0).length} of ${rows.length}\n\n`;
md += "## Flagged files\n\n";
if (!flagged.length) md += "none\n";
for (const r of flagged) {
  md += `- ${r.spec} ${r.cond} ${r.trial}`;
  if (r.outsideSpec.length) md += `; names not in spec: ${r.outsideSpec.join(", ")}`;
  if (r.behaviours.length) md += `; ${r.behaviours.join(", ")}`;
  if (r.mentions.length) md += `; comments: ${r.mentions.map((m) => JSON.stringify(m)).join(" | ")}`;
  md += "\n";
}
md += "\n## Per-file detail\n\n| Spec | Condition | Trial | Module names used | Outside own spec | False-alarm tests |\n|---|---|---|---|---|---|\n";
for (const r of rows) md += `| ${r.spec} | ${r.cond} | ${r.trial} | ${r.names.length} | ${r.outsideSpec.length ? r.outsideSpec.join(", ") : "none"} | ${r.falseAlarms} |\n`;

fs.writeFileSync(path.join(ROOT, "results", "isolation_audit.md"), md);
console.log(md.split("## Per-file detail")[0]);
