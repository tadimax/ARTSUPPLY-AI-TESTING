"use strict";

// Reads results/runs.jsonl and results/faults_status.json, writes results/summary.md.
// Usage: node scripts/analyze.js

const fs = require("node:fs");
const path = require("node:path");
const ROOT = path.resolve(__dirname, "..");
const rows = fs.readFileSync(path.join(ROOT, "results", "runs.jsonl"), "utf8").trim().split("\n").map((l) => JSON.parse(l));
const faults = JSON.parse(fs.readFileSync(path.join(ROOT, "results", "faults_status.json"), "utf8"));

const gen = rows.filter((r) => r.source === "generated");
const conds = ["basic", "structured"];
const specs = [...new Set(gen.map((r) => r.spec))].sort();
const sum = (a, f) => a.reduce((s, x) => s + f(x), 0);
const pct = (n, d) => (d ? (100 * n / d).toFixed(1) + "%" : "n/a");
const mean = (a) => (a.length ? sum(a, (x) => x) / a.length : 0);

// A fault is "counted" only if some file anywhere killed it (otherwise it may be an equivalent mutant).
const counted = new Set(faults.filter((f) => f.killedByAnyFile).map((f) => f.id));
const excluded = faults.filter((f) => !f.killedByAnyFile).map((f) => f.id);

let md = "# Results summary\n\nGenerated by scripts/analyze.js from results/runs.jsonl. Do not edit by hand.\n\n";

md += "## Per condition (all specs, all trials)\n\n| Condition | Files | Compiled | Tests | Mean tests per file | Tests failing on correct code | Files with a false alarm | Faults killed (all faults) | Faults killed (excluding never-killed faults) |\n|---|---|---|---|---|---|---|---|---|\n";
for (const c of conds) {
  const g = gen.filter((r) => r.condition === c);
  const fk = sum(g, (r) => r.killed.length), ft = sum(g, (r) => r.faultsTotal);
  const fkc = sum(g, (r) => r.killed.filter((id) => counted.has(id)).length);
  const ftc = sum(g, (r) => faults.filter((f) => f.spec === r.spec && counted.has(f.id)).length);
  md += `| ${c} | ${g.length} | ${g.filter((r) => r.loaded).length} | ${sum(g, (r) => r.testsTotal)} | ${mean(g.map((r) => r.testsTotal)).toFixed(1)} | ${sum(g, (r) => r.falseAlarms)} | ${g.filter((r) => r.falseAlarms > 0).length} | ${fk}/${ft} (${pct(fk, ft)}) | ${fkc}/${ftc} (${pct(fkc, ftc)}) |\n`;
}

md += "\n## Per specification (kill rate = killed / (faults x trials))\n\n| Spec | Faults | basic kill rate | structured kill rate | basic false-alarm tests | structured false-alarm tests |\n|---|---|---|---|---|---|\n";
for (const s of specs) {
  const nf = faults.filter((f) => f.spec === s).length;
  const cell = (c) => {
    const g = gen.filter((r) => r.spec === s && r.condition === c);
    const k = sum(g, (r) => r.killed.length);
    return [`${k}/${nf * g.length} (${pct(k, nf * g.length)})`, sum(g, (r) => r.falseAlarms)];
  };
  const b = cell("basic"), st = cell("structured");
  md += `| ${s} | ${nf} | ${b[0]} | ${st[0]} | ${b[1]} | ${st[1]} |\n`;
}

md += "\n## Faults that at least one trial missed (survivors)\n\n| Fault | Description | basic survivals (of 3) | structured survivals (of 3) | Killed by any file |\n|---|---|---|---|---|\n";
for (const f of faults) {
  const g = gen.filter((r) => r.spec === f.spec);
  const sb = g.filter((r) => r.condition === "basic" && r.survived.includes(f.id)).length;
  const ss = g.filter((r) => r.condition === "structured" && r.survived.includes(f.id)).length;
  if (sb + ss > 0 || !f.killedByAnyFile) md += `| ${f.id} | ${f.desc} | ${sb} | ${ss} | ${f.killedByAnyFile ? "yes" : "NO (possible equivalent mutant)"} |\n`;
}

md += "\n## Tests that fail on the correct code (false alarms), by spec\n\n";
for (const r of gen.filter((x) => x.falseAlarms > 0)) {
  md += `- ${r.spec} ${r.condition} ${r.trial}: ${r.falseAlarmNames.map((n) => JSON.stringify(n)).join("; ")}\n`;
}

const hum = rows.filter((r) => r.source === "human");
if (hum.length) {
  md += "\n## Human baseline (ArtSupply's own tests, S9 only)\n\nCovers specification S9 only; the other human tests in ArtSupply depend on modules that are not in this repo. Compared with the AI files for S9.\n\n| Source | Files | Tests | Tests failing on correct code | Faults killed (S9) |\n|---|---|---|---|---|\n";
  const s9 = (c) => gen.filter((r) => r.spec === "S9" && r.condition === c);
  for (const [label, g] of [["human", hum], ["basic (AI)", s9("basic")], ["structured (AI)", s9("structured")]]) {
    const k = sum(g, (r) => r.killed.length), t = sum(g, (r) => r.faultsTotal);
    md += `| ${label} | ${g.length} | ${sum(g, (r) => r.testsTotal)} | ${sum(g, (r) => r.falseAlarms)} | ${k}/${t} (${pct(k, t)}) |\n`;
  }
  for (const r of hum) {
    const miss = r.survived.length ? r.survived.join(", ") : "none";
    md += `\nFaults the human S9 file missed: ${miss}\n`;
  }
}

md += `\n## Faults never killed by any file\n\n${excluded.length ? excluded.join(", ") : "none"}\n`;
md += `\n## Faults hit by a run error (timeout or no tests ran)\n\n${rows.flatMap((r) => r.faultRunErrors.map((e) => `${r.spec}/${r.condition}/${r.trial}/${r.source}: ${e}`)).join("\n") || "none"}\n`;

fs.writeFileSync(path.join(ROOT, "results", "summary.md"), md);
console.log(md);
